"""Write the server status report for the `server-reports` branch (pushed hourly by deploy/push_reports.sh).

usage: python scripts/server_report.py OUT_DIR
  OUT_DIR/README.md          current status: bots, PnL by day, last trades, server health, code version
  OUT_DIR/days/<date>.md     the same snapshot, one file per UTC day (overwritten during the day)
  OUT_DIR/settles.csv        every settled window of the last 14 days (all bots) for analysis
  OUT_DIR/runs/<unit>.txt    scripts/report_journal.py of the current run of every running bot
  OUT_DIR/reviews/<day>.md   nightly reviews with experiment verdicts (scripts/nightly_review.py)
No secrets: only journals, risk state files and system stats are read.
"""
import csv
import os
import shutil
import subprocess
import sys
import time
from datetime import datetime, timezone

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from pmbot import ops  # noqa: E402


def main(out):
    os.makedirs(os.path.join(out, "days"), exist_ok=True)
    os.makedirs(os.path.join(out, "runs"), exist_ok=True)
    now = datetime.now(timezone.utc)
    md = [f"# Server status {now:%Y-%m-%d %H:%M} UTC", "",
          "Generated by `scripts/server_report.py` on the server. Do not edit: overwritten every hour.", "",
          "## Bots", "```", ops.format_status(), "```", "",
          "## PnL by day", "```", ops.format_pnl(days=30), "```", "",
          "## Last 30 settled windows", "```", ops.format_trades(30), "```", "",
          "## Server", "```", ops.format_server(), "```"]
    text = "\n".join(md) + "\n"
    open(os.path.join(out, "README.md"), "w").write(text)
    open(os.path.join(out, "days", f"{now:%Y-%m-%d}.md"), "w").write(text)

    rows = []
    for unit in ops.BOT_UNITS:
        journal, _, mode = ops.bot_paths(unit)
        if not journal:
            continue
        for e in ops.events_since(journal, time.time() - 14 * 86400):
            if e["type"] == "settle":
                rows.append({"time_utc": datetime.fromtimestamp(e["t"], timezone.utc).strftime("%Y-%m-%d %H:%M:%S"),
                             "unit": unit, "mode": mode, "key": e.get("key"), "winner": e.get("winner"),
                             "up": e.get("up"), "down": e.get("down"), "cost": e.get("cost"),
                             "payoff": e.get("payoff"), "rebate": e.get("rebate"), "pnl": e.get("pnl")})
    rows.sort(key=lambda r: r["time_utc"])
    with open(os.path.join(out, "settles.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["time_utc", "unit", "mode", "key", "winner", "up", "down", "cost",
                                          "payoff", "rebate", "pnl"])
        w.writeheader()
        w.writerows(rows)

    rev = os.path.join(ops.REPO, "data", "reviews")         # nightly reviews (scripts/nightly_review.py)
    if os.path.isdir(rev):
        os.makedirs(os.path.join(out, "reviews"), exist_ok=True)
        for name in sorted(os.listdir(rev))[-60:]:
            if name.endswith(".md"):
                shutil.copyfile(os.path.join(rev, name), os.path.join(out, "reviews", name))

    for unit in ops.BOT_UNITS:
        if ops.unit_state(unit)[0] != "active":
            continue
        journal, _, _ = ops.bot_paths(unit)
        dirs = ops.run_dirs(journal) if journal else []
        if not dirs:
            continue
        r = subprocess.run([sys.executable, os.path.join(ops.REPO, "scripts", "report_journal.py"), dirs[-1]],
                           capture_output=True, text=True, timeout=300, cwd=ops.REPO)
        open(os.path.join(out, "runs", f"{unit}.txt"), "w").write(r.stdout[-20000:] + r.stderr[-2000:])


if __name__ == "__main__":
    main(sys.argv[1])
